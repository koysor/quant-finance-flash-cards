"""
Render the whole site to static files that a web server (Caddy) can serve.

Every page is a pure function of the files loaded at startup, so the build asks
the Flask app for each URL through its test client and writes the response to a
file.  ``STATIC_BUILD`` is set in the app config so the few dynamic routes render
browser-side stand-ins (see ``app/routes.py``).  Requests carry
``X-Forwarded-Prefix``, exactly as Caddy sends it, so every ``url_for`` link
includes the prefix the site is served under.

File layout: ``/`` → ``index.html``; ``/a/b`` → ``a/b.html``; URLs ending in
``.json`` keep their name.  The server maps a request for ``/a/b`` to
``a/b.html`` (Caddy: ``try_files {path} {path}.html``).  ``404.html`` is the
not-found page, and ``app/static`` is copied to ``static/``.

No compressed copies are written: Caddy's ``encode`` compresses on the fly
(about 14 ms for the 2.3 MB graph page), and its ``precompressed`` option makes
Caddy 2.10 answer ordinary requests with 206 Partial Content.  The build fails
if any page links to a file that was not written.
"""

import html
import os
import re
import shutil
import time
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from urllib.parse import unquote

from flask import Flask, url_for

from app.db import get_all_cards
from app.extensions import cache, limiter
from app.routes import TOPIC_BY_SLUG

#: Marks a directory as build output, so a rebuild only ever deletes its own files.
MARKER = ".flashcards-static-build"

#: A segment that cannot safely be a file or directory name.  The site is served
#: from Linux, where only these are a problem; Windows also forbids ``:*?"<>|``
#: (the ``P(A|B)`` tag, for one), so a full build has to run on Linux.
_BAD_SEGMENT = re.compile(
    r"^\.{1,2}$|[\x00-\x1f\\]" + (r'|[:*?"<>|]' if os.name == "nt" else "")
)

_LINK_RE = re.compile(r'(?:href|src)="([^"]*)"')


class BuildError(RuntimeError):
    """A page failed to render, could not be stored, or a link points nowhere."""


@dataclass
class BuildResult:
    out: Path
    pages: int = 0
    files: int = 0
    bytes: int = 0
    seconds: float = 0.0
    missing_links: list[str] = field(default_factory=list)


def page_urls(app: Flask) -> list[str]:
    """Every URL to render, unprefixed and URL-quoted, as ``url_for`` builds them."""
    with app.test_request_context():
        cards = [dict(c) for c in get_all_cards()]
        tags = sorted(
            {t.strip() for c in cards for t in c["tags"].split(",") if t.strip()}
        )
        topics = sorted({c["topic"] for c in cards})
        slugs = {v: k for k, v in TOPIC_BY_SLUG.items()}
        urls = [
            url_for("main.index"),
            url_for("main.graph_view"),
            url_for("main.formulas"),
            url_for("main.recent"),
            url_for("main.quiz"),
            url_for("main.search_data_json_view"),
            url_for("main.random_card"),
            url_for("main.barbie_theme"),
        ]
        for topic in topics:
            if topic in slugs:
                urls.append(url_for("main.topic_page", slug=slugs[topic]))
                urls.append(url_for("main.quiz_topic", slug=slugs[topic]))
        for c in cards:
            urls.append(url_for("main.card_detail", card_id=c["id"]))
            urls.append(url_for("main.study_path", card_id=c["id"]))
        urls += [url_for("main.tag_page", tag=t) for t in tags]
    return urls


def url_to_file(url: str) -> PurePosixPath:
    """Map an unprefixed URL path to its file, relative to the output directory."""
    path = unquote(url.split("?", 1)[0])
    if path in ("", "/"):
        return PurePosixPath("index.html")
    parts = path.strip("/").split("/")
    for seg in parts:
        if not seg or _BAD_SEGMENT.search(seg):
            hint = " (build on Linux, e.g. WSL or Docker)" if os.name == "nt" else ""
            raise BuildError(f"{url!r}: {seg!r} cannot be a file name here{hint}")
    rel = PurePosixPath(*parts)
    return rel if rel.suffix == ".json" else rel.with_name(rel.name + ".html")


def _prepare_out(out: Path) -> None:
    """Empty *out*, refusing to touch a non-empty directory the build did not make."""
    if out.exists():
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise BuildError(f"{out} is not empty and is not a previous build")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("Generated by scripts/build_static.py\n")


def _write(out: Path, rel: PurePosixPath, data: bytes) -> Path:
    dest = out / rel
    if dest.exists():
        # On a case-insensitive file system two URLs can land on one file.
        raise BuildError(f"{rel} written twice (URLs differ only in case?)")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return dest


def _resolves(out: Path, path: str) -> bool:
    """Whether a site-relative URL path is served by a file in *out*."""
    if path in ("", "/"):
        return (out / "index.html").is_file()
    rel = unquote(path).strip("/")
    if not rel or ".." in rel.split("/"):
        return False
    return (out / rel).is_file() or (out / (rel + ".html")).is_file()


def find_missing_links(out: Path, prefix: str) -> list[str]:
    """Links under *prefix* in the generated pages that no file serves."""
    base = prefix.rstrip("/") + "/"
    missing: set[str] = set()
    for page in out.rglob("*.html"):
        for raw in _LINK_RE.findall(page.read_text(encoding="utf-8")):
            link = html.unescape(raw).split("#", 1)[0].split("?", 1)[0]
            if not link.startswith(base) and link != prefix:
                continue  # external, relative or fragment-only
            if not _resolves(out, link[len(base) :]):
                missing.add(link)
    return sorted(missing)


def build(
    app: Flask, out: Path, prefix: str = "", urls: Iterable[str] | None = None
) -> BuildResult:
    """
    Render the site into *out* as served under *prefix* (``""`` or ``/flashcards``).

    *urls* defaults to every page (``page_urls``); tests pass a subset.  Raises
    ``BuildError`` if a page does not return 200, or if a page links to a file
    that was not written (only checked for a full build).
    """
    started = time.perf_counter()
    prefix = prefix.rstrip("/")
    full = urls is None
    # Pages rendered before the build lack the static stand-ins, and pages
    # rendered during it must not be served by the live app afterwards.
    with app.app_context():
        cache.clear()
    app.config["STATIC_BUILD"] = True
    limiter.enabled = False  # thousands of requests from one "client"
    headers = {"X-Forwarded-Prefix": prefix} if prefix else {}
    client = app.test_client()

    _prepare_out(out)
    result = BuildResult(out=out)

    def fetch(url: str, expect: int = 200) -> bytes:
        resp = client.get(url, headers=headers)
        if resp.status_code != expect:
            raise BuildError(f"{url} returned {resp.status_code}, expected {expect}")
        return resp.get_data()

    try:
        for url in page_urls(app) if full else urls:
            _write(out, url_to_file(url), fetch(url))
            result.pages += 1
        with app.test_request_context():
            recent_url = url_for("main.recent", format="json")
        _write(out, PurePosixPath("recent.json"), fetch(recent_url))
        _write(out, PurePosixPath("404.html"), fetch("/__static-build-404__", 404))
    finally:
        app.config["STATIC_BUILD"] = False
        limiter.enabled = True
        with app.app_context():
            cache.clear()

    if app.static_folder:
        shutil.copytree(app.static_folder, out / "static")

    if full:
        result.missing_links = find_missing_links(out, prefix or "")
        if result.missing_links:
            shown = "\n  ".join(result.missing_links[:20])
            raise BuildError(
                f"{len(result.missing_links)} links point to no file:\n  {shown}"
            )

    for root, _dirs, files in os.walk(out):
        for name in files:
            result.files += 1
            result.bytes += os.path.getsize(os.path.join(root, name))
    result.seconds = time.perf_counter() - started
    return result
